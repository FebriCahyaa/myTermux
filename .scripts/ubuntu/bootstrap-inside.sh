#!/usr/bin/env bash
# Executed as the simulated root account inside proot-distro. Idempotent by design.
set -Eeuo pipefail

UBUNTU_USER="${1:-developer}"
UBUNTU_HOST="${2:-ubuntu-dev}"
export DEBIAN_FRONTEND=noninteractive
export TZ="${TZ:-Asia/Jakarta}"

if [[ ! "$UBUNTU_USER" =~ ^[a-z_][a-z0-9_-]{0,31}$ || "$UBUNTU_USER" == "root" ]]; then
  echo "Invalid Ubuntu username: $UBUNTU_USER" >&2
  exit 2
fi
if [[ ! "$UBUNTU_HOST" =~ ^[A-Za-z0-9][A-Za-z0-9-]{0,62}$ ]]; then
  echo "Invalid Ubuntu host label: $UBUNTU_HOST" >&2
  exit 2
fi

log() { printf '\033[1;34m[ubuntu-bootstrap]\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[warning]\033[0m %s\n' "$*" >&2; }

log "Refreshing package indexes..."
apt-get update

# Package names vary slightly between Ubuntu releases and CPU architectures. Install
# all packages that exist in the configured Ubuntu repositories; skipped items are
# reported instead of causing the entire bootstrap to fail.
install_available() {
  local package
  local -a available=()
  local -a skipped=()
  for package in "$@"; do
    if apt-cache show "$package" >/dev/null 2>&1; then
      available+=("$package")
    else
      skipped+=("$package")
    fi
  done
  if ((${#available[@]})); then
    log "Installing ${#available[@]} packages..."
    apt-get -o Dpkg::Options::=--force-confdef -o Dpkg::Options::=--force-confold install -y --no-install-recommends "${available[@]}"
  fi
  if ((${#skipped[@]})); then
    warn "Packages unavailable on this Ubuntu image: ${skipped[*]}"
  fi
}

BASE_PACKAGES=(
  ca-certificates curl wget gnupg lsb-release locales tzdata apt-utils
  git git-lfs openssh-client zsh bash-completion tmux neovim fzf ripgrep
  fd-find jq tree htop file less nano vim python3 python3-pip python3-venv
  aria2 ncdu lsof procps dnsutils iproute2 net-tools openssl sqlite3 man-db manpages parallel
  bat eza p7zip-full yq
  python3-dev python-is-python3 python3-setuptools python3-wheel python3-yaml python3-numpy
  shellcheck shfmt starship rsync unzip zip xz-utils zstd
)

KERNEL_PACKAGES=(
  build-essential clang lld llvm gcc g++ make cmake ninja-build meson
  pkg-config ccache binutils bc bison flex gperf device-tree-compiler
  libelf-dev libssl-dev libncurses-dev libxml2-utils xsltproc dwarves pahole
  lz4 lzop liblz4-tool git-lfs python3-dev python3-setuptools libz-dev
  libbz2-dev liblzma-dev libarchive-dev liblz4-dev libzstd-dev libxml2-dev
  libpng-dev libjpeg-dev libglib2.0-dev libffi-dev libsqlite3-dev
  libreadline-dev libcap-dev libpcre2-dev libevent-dev protobuf-compiler
  libprotobuf-dev libusb-1.0-0-dev squashfs-tools cpio
)

ANDROID_PACKAGES=(
  default-jdk openjdk-17-jdk openjdk-21-jdk repo adb fastboot
  android-tools-adb android-tools-fastboot android-sdk-platform-tools
  android-sdk-build-tools git-review imagemagick pngcrush fontconfig
  schedtool libxml2-utils python3-pip nodejs npm cargo rustc
  gcc-multilib g++-multilib libc6-dev-i386 lib32ncurses-dev lib32z1-dev
  libgl1-mesa-dev libx11-dev lzip erofs-utils android-sdk-libsparse-utils
)

log "Upgrading base packages..."
apt-get -o Dpkg::Options::=--force-confdef -o Dpkg::Options::=--force-confold full-upgrade -y
install_available "${BASE_PACKAGES[@]}"
install_available "${KERNEL_PACKAGES[@]}"
install_available "${ANDROID_PACKAGES[@]}"

# Prefer the distribution's repo package. If it is missing, try Google's official
# repo launcher as a best-effort fallback. Failure is non-fatal; users can install it later.
if ! command -v repo >/dev/null 2>&1; then
  if command -v curl >/dev/null 2>&1; then
    log "The 'repo' package was not available; trying Google's repo launcher..."
    if curl -fsSL https://storage.googleapis.com/git-repo-downloads/repo -o /usr/local/bin/repo; then
      chmod 0755 /usr/local/bin/repo
    else
      rm -f /usr/local/bin/repo
      warn "Could not download repo launcher; install it manually if ROM sync requires it."
    fi
  fi
fi

if command -v git-lfs >/dev/null 2>&1; then
  git lfs install --system >/dev/null 2>&1 || true
fi

# Record the configured hostname label. The login wrapper also passes --hostname so
# hostname calls inside PRoot see it; Android's real host/kernel hostname is unchanged.
printf '%s\n' "$UBUNTU_HOST" > /etc/hostname
mkdir -p /mnt/termux-home
cat > /etc/profile.d/mytermux-profile.sh <<EOF_PROFILE
# Generated by myTermux. The name/host below affect the prompt only.
export MYTERMUX_ENV='ubuntu'
export MYTERMUX_HOST='${UBUNTU_HOST}'
export TERMUX_HOME='/mnt/termux-home'
if [ "\$(id -u 2>/dev/null || echo 1)" -eq 0 ]; then
  export MYTERMUX_USER='root'
else
  export MYTERMUX_USER='${UBUNTU_USER}'
fi
EOF_PROFILE
chmod 0644 /etc/profile.d/mytermux-profile.sh

if ! id "$UBUNTU_USER" >/dev/null 2>&1; then
  log "Creating non-root Ubuntu account: ${UBUNTU_USER}"
  LOGIN_SHELL="$(command -v zsh || command -v bash || printf /bin/bash)"
  useradd --create-home --shell "$LOGIN_SHELL" "$UBUNTU_USER"
else
  LOGIN_SHELL="$(command -v zsh || command -v bash || printf /bin/bash)"
  usermod --shell "$LOGIN_SHELL" "$UBUNTU_USER"
  mkdir -p "/home/${UBUNTU_USER}"
fi

write_starship_config() {
  local target="$1"
  mkdir -p "$(dirname "$target")"
  cat > "$target" <<'EOF_STARSHIP'
add_newline = false
command_timeout = 800
palette = "macpro"
format = """
$env_var.MYTERMUX_USER$env_var.MYTERMUX_HOST$directory$git_branch$git_status
$character"""
[palettes.macpro]
green = "#A6E3A1"
blue = "#89B4FA"
purple = "#CBA6F7"
yellow = "#F9E2AF"
red = "#F38BA8"
muted = "#A6ADC8"
[env_var.MYTERMUX_USER]
variable = "MYTERMUX_USER"
default = "developer"
format = "[$env_value](bold green)"
[env_var.MYTERMUX_HOST]
variable = "MYTERMUX_HOST"
default = "ubuntu-dev"
format = "[@$env_value](bold blue) "
[directory]
style = "bold purple"
format = "[$path]($style) "
truncation_length = 3
truncation_symbol = "…/"
[git_branch]
symbol = " "
style = "yellow"
format = "[$symbol$branch]($style) "
[git_status]
style = "yellow"
format = "[$all_status$ahead_behind]($style) "
[cmd_duration]
min_time = 1500
format = "[took $duration](dimmed yellow) "
[character]
success_symbol = "[❯](bold green)"
error_symbol = "[❯](bold red)"
vimcmd_symbol = "[❮](bold yellow)"
EOF_STARSHIP
  chmod 0644 "$target"
}

configure_home() {
  local home_dir="$1"
  local account_name="$2"
  mkdir -p "$home_dir/.config/mytermux" "$home_dir/.config"
  write_starship_config "$home_dir/.config/starship.toml"

  cat > "$home_dir/.config/mytermux/prompt.zsh" <<EOF_ZSH
export MYTERMUX_ENV='ubuntu'
export MYTERMUX_HOST='${UBUNTU_HOST}'
export TERMUX_HOME='/mnt/termux-home'
if [[ \${EUID:-1} -eq 0 ]]; then
  export MYTERMUX_USER='root'
else
  export MYTERMUX_USER='${account_name}'
fi
if command -v starship >/dev/null 2>&1; then
  export STARSHIP_CONFIG="\$HOME/.config/starship.toml"
  eval "\$(starship init zsh)"
else
  autoload -Uz colors && colors
  setopt PROMPT_SUBST
  PROMPT="%F{green}\${MYTERMUX_USER}%f@%F{blue}\${MYTERMUX_HOST}%f %F{magenta}%3~%f"\$'\\n'"%F{green}❯%f "
fi
alias ll='ls -alF'
alias la='ls -A'
alias grep='grep --color=auto'
alias cdtermux='cd /mnt/termux-home'
function mkcd() { [[ \$# -eq 1 ]] || { echo "Usage: mkcd DIRECTORY" >&2; return 2; }; mkdir -p -- "\$1" && cd -- "\$1"; }
EOF_ZSH

  cat > "$home_dir/.config/mytermux/prompt.bash" <<EOF_BASH
export MYTERMUX_ENV='ubuntu'
export MYTERMUX_HOST='${UBUNTU_HOST}'
export TERMUX_HOME='/mnt/termux-home'
if [ "\$(id -u 2>/dev/null || echo 1)" -eq 0 ]; then
  export MYTERMUX_USER='root'
else
  export MYTERMUX_USER='${account_name}'
fi
if [[ \$- == *i* ]]; then
  if command -v starship >/dev/null 2>&1; then
    export STARSHIP_CONFIG="\$HOME/.config/starship.toml"
    eval "\$(starship init bash)"
  else
    PS1="\\[\\e[1;32m\\]\${MYTERMUX_USER}\\[\\e[0m\\]@\\[\\e[1;34m\\]\${MYTERMUX_HOST}\\[\\e[0m\\] \\[\\e[1;35m\\]\\w\\[\\e[0m\\]\\n\\[\\e[1;32m\\]❯\\[\\e[0m\\] "
  fi
fi
EOF_BASH

  touch "$home_dir/.zshrc" "$home_dir/.bashrc"
  grep -Fq 'mytermux/prompt.zsh' "$home_dir/.zshrc" || printf '\n[[ -r "$HOME/.config/mytermux/prompt.zsh" ]] && source "$HOME/.config/mytermux/prompt.zsh"\n' >> "$home_dir/.zshrc"
  grep -Fq 'mytermux/prompt.bash' "$home_dir/.bashrc" || printf '\n[[ -r "$HOME/.config/mytermux/prompt.bash" ]] && source "$HOME/.config/mytermux/prompt.bash"\n' >> "$home_dir/.bashrc"
}

configure_home /root root
configure_home "/home/${UBUNTU_USER}" "$UBUNTU_USER"
USER_GROUP="$(id -gn "$UBUNTU_USER")"
chown -R "${UBUNTU_USER}:${USER_GROUP}" "/home/${UBUNTU_USER}"

# Keep the root and non-root shells usable without relying on sudo inside PRoot.
# Use `ubroot` from Termux for package operations; it explicitly opens this root shell.
log "Ubuntu ready: ${UBUNTU_USER}@${UBUNTU_HOST}"
log "For package administration, exit to Termux and run: ubroot"
log "Finished. Note: PRoot cannot grant real Android root or change the host kernel."
