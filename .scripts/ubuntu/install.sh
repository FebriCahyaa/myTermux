#!/usr/bin/env bash
# Install a full Ubuntu proot userland and Android/kernel development toolchain.
set -Eeuo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
CONFIG_DIR="${HOME}/.config/mytermux"
PROFILE_FILE="${CONFIG_DIR}/ubuntu-profile.env"

log() { printf '\033[1;34m[ubuntu-install]\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[warning]\033[0m %s\n' "$*" >&2; }
fail() { printf '\033[1;31m[error]\033[0m %s\n' "$*" >&2; exit 1; }

[[ -n "${PREFIX:-}" && -x "${PREFIX}/bin/pkg" ]] || fail "This installer must run in Termux."
[[ -r "$PROFILE_FILE" ]] || fail "Missing $PROFILE_FILE. Run ./install.sh first to configure usernames and hosts."
# The profile is generated by our installer and only contains validated identifiers.
# shellcheck source=/dev/null
source "$PROFILE_FILE"
UBUNTU_DISTRO="${UBUNTU_DISTRO:-ubuntu}"
UBUNTU_IMAGE="${UBUNTU_IMAGE:-ubuntu:24.04}"
UBUNTU_USER="${UBUNTU_USER:-developer}"
UBUNTU_HOST="${UBUNTU_HOST:-ubuntu-dev}"

if ! command -v proot-distro >/dev/null 2>&1; then
  log "Installing proot-distro in Termux..."
  pkg update
  pkg install -y proot-distro proot
fi

ROOTFS_LEGACY="${PREFIX}/var/lib/proot-distro/installed-rootfs/${UBUNTU_DISTRO}"
ROOTFS_CURRENT="${PREFIX}/var/lib/proot-distro/containers/${UBUNTU_DISTRO}/rootfs"
if proot-distro list --quiet 2>/dev/null | grep -Fxq "$UBUNTU_DISTRO"; then
  log "Found existing ${UBUNTU_DISTRO} container; keeping existing files and projects."
elif [[ ! -d "$ROOTFS_LEGACY" && ! -d "$ROOTFS_CURRENT" ]]; then
  log "Installing ${UBUNTU_DISTRO} root filesystem. This download may be large."
  proot-distro install "$UBUNTU_IMAGE"
else
  log "Found existing ${UBUNTU_DISTRO} root filesystem; keeping existing files and projects."
fi

[[ -r "${SCRIPT_DIR}/bootstrap-inside.sh" ]] || fail "Missing bootstrap-inside.sh beside this script."
log "Installing/updating Ubuntu dependencies and setting up ${UBUNTU_USER}@${UBUNTU_HOST}..."
# Feed the bootstrap script to Bash inside the distro. The script takes the validated
# Ubuntu account and prompt host as positional parameters.
proot-distro login --hostname "$UBUNTU_HOST" --shared-tmp "$UBUNTU_DISTRO" -- /bin/bash -s -- "$UBUNTU_USER" "$UBUNTU_HOST" < "${SCRIPT_DIR}/bootstrap-inside.sh"

log "Ubuntu setup finished. Use: ubuntu (normal user), ubroot (administration shell)."
log "PRoot is a userspace environment, not Android root and not a virtual machine."
